CREATE TABLE IF NOT EXISTS product (
    id       BIGINT NOT NULL PRIMARY KEY,
    quantity BIGINT NOT NULL,
    version  BIGINT
);

CREATE TABLE IF NOT EXISTS product_reserve (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    order_id     BIGINT NOT NULL,
    quantity     BIGINT NOT NULL,
    CONSTRAINT uk_product_reserve_order_id UNIQUE (order_id)
);

CREATE TABLE IF NOT EXISTS product_product_reserve (
    product_reserve_id BIGINT NOT NULL,
    product_id         BIGINT NOT NULL,
    CONSTRAINT fk_ppr_product_reserve FOREIGN KEY (product_reserve_id) REFERENCES product_reserve (id),
    CONSTRAINT fk_ppr_product         FOREIGN KEY (product_id)         REFERENCES product (id)
);
CREATE INDEX IF NOT EXISTS idx_ppr_product_reserve_id ON product_product_reserve (product_reserve_id);
CREATE INDEX IF NOT EXISTS idx_ppr_product_id         ON product_product_reserve (product_id);
