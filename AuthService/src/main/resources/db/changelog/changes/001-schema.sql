CREATE TABLE IF NOT EXISTS users (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_time TIMESTAMPTZ  NOT NULL DEFAULT now(),
    first_name   VARCHAR(255) NOT NULL,
    last_name    VARCHAR(255) NOT NULL,
    email        VARCHAR(255) NOT NULL,
    phone        VARCHAR(255) NOT NULL,
    password     VARCHAR(255) NOT NULL,
    state        VARCHAR(255) NOT NULL DEFAULT 'ACTIVE',
    deleted      BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_state CHECK (state IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role    VARCHAR(255) NOT NULL,
    PRIMARY KEY (user_id, role),
    CONSTRAINT ck_user_roles_role CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_time TIMESTAMPTZ NOT NULL DEFAULT now(),
    token_hash   VARCHAR(64) NOT NULL,
    user_id      BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    expires_at   TIMESTAMPTZ NOT NULL,
    revoked      BOOLEAN     NOT NULL DEFAULT FALSE,
    revoked_at   TIMESTAMPTZ,
    CONSTRAINT uk_refresh_tokens_hash UNIQUE (token_hash)
);
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id ON refresh_tokens (user_id);

CREATE TABLE IF NOT EXISTS oauth_clients (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_time      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    client_id         VARCHAR(64)  NOT NULL,
    name              VARCHAR(255) NOT NULL,
    description       VARCHAR(255),
    contact_email     VARCHAR(255),
    secret_hash       VARCHAR(255) NOT NULL,
    enabled           BOOLEAN      NOT NULL DEFAULT TRUE,
    secret_rotated_at TIMESTAMPTZ,
    CONSTRAINT uk_oauth_clients_client_id UNIQUE (client_id)
);

CREATE TABLE IF NOT EXISTS oauth_client_scopes (
    client_id BIGINT       NOT NULL REFERENCES oauth_clients (id) ON DELETE CASCADE,
    scope     VARCHAR(255) NOT NULL,
    PRIMARY KEY (client_id, scope)
);
