CREATE TABLE IF NOT EXISTS customer (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_time  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    name          VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    phone         VARCHAR(255) NOT NULL,
    date_of_birth TIMESTAMP(6),
    address       VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS product (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    name         VARCHAR(255) NOT NULL,
    decription   VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_time  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    customer_id   BIGINT REFERENCES customer (id),
    currency      VARCHAR(32),
    order_address VARCHAR(255),
    status        VARCHAR(32)
);
CREATE INDEX IF NOT EXISTS idx_orders_customer_id ON orders (customer_id);

CREATE TABLE IF NOT EXISTS order_product (
    order_id   BIGINT NOT NULL REFERENCES orders (id),
    product_id BIGINT NOT NULL REFERENCES product (id)
);
CREATE INDEX IF NOT EXISTS idx_order_product_order_id   ON order_product (order_id);
CREATE INDEX IF NOT EXISTS idx_order_product_product_id ON order_product (product_id);

CREATE TABLE IF NOT EXISTS outbox_event (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    updated_time TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    event_type   VARCHAR(64)   NOT NULL,
    aggregate_id VARCHAR(64)   NOT NULL,
    payload      TEXT          NOT NULL,
    published_at TIMESTAMP(6) WITH TIME ZONE,
    attempts     INTEGER       NOT NULL,
    last_error   VARCHAR(1000)
);
CREATE INDEX IF NOT EXISTS idx_outbox_event_published_at ON outbox_event (published_at);
